    private fun extractSharedUrlOrText(rawText: String): String {
        val trimmed = rawText.trim()
        val urlMatch = Regex("""https?://[^\s"'<>]+""", RegexOption.IGNORE_CASE).find(trimmed)
        if (urlMatch != null) {
            return urlMatch.value.trimEnd('.', ',', ')', ']', ';', '!', '?')
        }
        return trimmed
    }

    private fun handleIntent(intent: Intent?) {
        if (intent == null) return
        var rawCandidate: String? = null
        if (intent.action == Intent.ACTION_SEND) {
            rawCandidate = intent.getStringExtra(Intent.EXTRA_TEXT)
                ?: intent.getStringExtra(Intent.EXTRA_SUBJECT)
            if (rawCandidate.isNullOrBlank() && intent.clipData != null && intent.clipData!!.itemCount > 0) {
                rawCandidate = intent.clipData!!.getItemAt(0)?.coerceToText(this)?.toString()
            }
        } else if (intent.action == Intent.ACTION_VIEW) {
            rawCandidate = intent.dataString
        }

        if (!rawCandidate.isNullOrBlank()) {
            val extracted = extractSharedUrlOrText(rawCandidate)
            if (extracted.isNotBlank()) {
                sharedUrl = extracted
                emitEvent(
                    mapOf(
                        "type" to "SHARED_URL",
                        "url" to extracted
                    )
                )
            }
        }
    }

    override fun configureFlutterEngine(@NonNull flutterEngine: FlutterEngine) {
        super.configureFlutterEngine(flutterEngine)

        // Setup EventChannel for live download events
        EventChannel(flutterEngine.dartExecutor.binaryMessenger, STREAM_CHANNEL)
            .setStreamHandler(object : EventChannel.StreamHandler {
                override fun onListen(arguments: Any?, events: EventChannel.EventSink?) {
                    synchronized(eventSinkLock) {
                        eventSink = events
                    }
                }

                override fun onCancel(arguments: Any?) {
                    synchronized(eventSinkLock) {
                        eventSink = null
                    }
                }
            })

        // Setup MethodChannel for synchronous and asynchronous actions
        MethodChannel(flutterEngine.dartExecutor.binaryMessenger, ENGINE_CHANNEL)
            .setMethodCallHandler { call: MethodCall, rawResult: MethodChannel.Result ->
                val safeResult = SafeResult(rawResult)

                when (call.method) {
                    "initEngine" -> {
                        executor.execute {
                            try {
                                ensureEngineInitialized()
                                safeResult.success(true)
                            } catch (e: Exception) {
                                val cleanError = extractCleanErrorMessage(e)
                                safeResult.error("INIT_ERROR", cleanError, e.message)
                            }
                        }
                    }

                    "getSharedUrl" -> {
                        val url = sharedUrl
                        sharedUrl = null // consume once
                        safeResult.success(url)
                    }

                    "getEngineVersions" -> {
                        executor.execute {
                            try {
                                ensureEngineInitialized()
                                val ytDlpVer = try {
                                    YoutubeDL.getInstance().version(applicationContext)?.takeIf { it.isNotBlank() } ?: "N/A"
                                } catch (_: Exception) {
                                    "N/A"
                                }
                                val nodeVer = try {
                                    val nodeFile = File(File(applicationContext.filesDir, "bin"), "node")
                                    if (nodeFile.exists() && nodeFile.length() > 0) {
                                        val process = Runtime.getRuntime().exec(arrayOf("sh", nodeFile.absolutePath, "-v"))
                                        val output = process.inputStream.bufferedReader().use { it.readLine() }?.trim()
                                        val finished = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
                                            process.waitFor(2, TimeUnit.SECONDS)
                                        } else {
                                            process.waitFor()
                                            true
                                        }
                                        if (finished && process.exitValue() == 0 && !output.isNullOrBlank()) {
                                            output
                                        } else {
                                            process.destroy()
                                            "N/A"
                                        }
                                    } else {
                                        "N/A"
                                    }
                                } catch (_: Exception) {
                                    "N/A"
                                }
                                val versions = mapOf(
                                    "ytdlp" to ytDlpVer,
                                    "ffmpeg" to "Embedded (4.4+)",
                                    "aria2c" to "Embedded (1.36+)",
                                    "node" to nodeVer,
                                    "av1_hw" to if (checkAv1HardwareAccelerated()) "Supported" else "Software"
                                )
                                safeResult.success(versions)
                            } catch (e: Exception) {
                                val emptyVersions = mapOf(
                                    "ytdlp" to "N/A",
                                    "ffmpeg" to "N/A",
                                    "aria2c" to "N/A",
                                    "node" to "N/A"
                                )
                                safeResult.success(emptyVersions)
                            }
                        }
                    }

                    "updateEngine" -> {
                        val channelArg = call.argument<String>("channel")?.trim() ?: "nightly"
                        executor.execute {
                            try {
                                ensureEngineInitialized()
                                val updateChannel = if (channelArg.equals("stable", ignoreCase = true)) {
                                    YoutubeDL.UpdateChannel.STABLE
                                } else {
                                    YoutubeDL.UpdateChannel.NIGHTLY
                                }
                                YoutubeDL.getInstance().updateYoutubeDL(applicationContext, updateChannel)
                                isJsRuntimesSupported = null
                                getOrCreateConfigFile()
                                val newVersion = YoutubeDL.getInstance().version(applicationContext)
                                    ?: "Updated (${channelArg.uppercase()})"
                                val displayVer = "$newVersion (${channelArg.uppercase()})"
                                safeResult.success(displayVer)
                            } catch (e: Exception) {
                                android.util.Log.e(TAG, "Update engine error: ${e.message}", e)
                                val cleanError = extractCleanErrorMessage(e)
                                safeResult.error("UPDATE_ERROR", cleanError, e.message)
                            }
                        }
                    }

                    "saveUserCookies" -> {
                        val content = call.argument<String>("content")?.trim() ?: ""
                        executor.execute {
                            try {
                                val f = getUserCookiesFile()
                                if (content.isEmpty()) {
                                    if (f.exists()) f.delete()
                                    safeResult.success("")
                                } else {
                                    val normalized = if (content.startsWith("# Netscape HTTP Cookie File")) {
                                        content
                                    } else {
                                        "$NETSCAPE_COOKIE_HEADER$content\n"
                                    }
                                    f.writeText(normalized)
                                    safeResult.success(f.absolutePath)
                                }
                            } catch (e: Exception) {
                                safeResult.error("COOKIE_SAVE_ERR", e.message)
                            }
                        }
                    }

                    "getUserCookies" -> {
                        executor.execute {
                            try {
                                val f = getUserCookiesFile()
                                safeResult.success(if (f.exists()) f.readText() else "")
                            } catch (_: Exception) {
                                safeResult.success("")
                            }
                        }
                    }

                    "getFormats" -> {
                        val rawUrl = call.argument<String>("url")?.trim()
                        val searchId = call.argument<String>("searchId")?.trim()?.takeIf { it.isNotEmpty() }
                            ?: "search_${System.currentTimeMillis()}"
                        val extraArgs = call.argument<List<String>>("extraArgs") ?: emptyList()

                        if (rawUrl.isNullOrEmpty()) {
                            safeResult.error("INVALID_URL", "Target URL cannot be empty")
                            return@setMethodCallHandler
                        }

                        executor.execute {
                            try {
                                ensureEngineInitialized()
                                val configFile = getOrCreateConfigFile()
                                val jsonRequest = YoutubeDLRequest(rawUrl)
                                jsonRequest.addOption("--config-locations", configFile.absolutePath)
                                jsonRequest.addOption("--dump-single-json")
                                jsonRequest.addOption("--no-warnings")

                                val lower = rawUrl.lowercase()
                                val isPlaylist = Regex("^[a-z]+search\\d*:").containsMatchIn(lower) ||
                                    lower.contains("/playlist") ||
                                    lower.contains("/sets/") ||
                                    lower.contains("/album/") ||
                                    lower.contains("/@") ||
                                    (lower.contains("list=") && !lower.contains("v="))
                                val isLive = lower.contains("/live/") ||
                                    lower.contains("/live?") ||
                                    lower.contains("twitch.tv/") ||
                                    lower.contains("kick.com/")

                                if (isPlaylist) {
                                    jsonRequest.addOption("--flat-playlist")
                                    jsonRequest.addOption("--ignore-errors")
                                } else if (isLive) {
                                    jsonRequest.addOption("--no-playlist")
                                    jsonRequest.addOption("--no-check-formats")
                                } else {
                                    jsonRequest.addOption("--no-playlist")
                                }

                                applyOptions(jsonRequest, extraArgs)

                                val jsonResponse: YoutubeDLResponse = YoutubeDL.getInstance().execute(jsonRequest, searchId, null)
                                val jsonOut = jsonResponse.out
                                if (jsonOut.isNullOrBlank()) {
                                    safeResult.error("FORMAT_EXTRACTION_FAILED", "yt-dlp returned empty JSON output for URL")
                                } else {
                                    safeResult.success(jsonOut)
                                }
                            } catch (e: Exception) {
                                if (isCancellationException(e)) {
                                    safeResult.error("SEARCH_CANCELLED", "Search cancelled by user")
                                } else {
                                    android.util.Log.e(TAG, "getFormats error: ${e.message}", e)
                                    val cleanError = extractCleanErrorMessage(e)
                                    safeResult.error("FORMAT_EXTRACTION_FAILED", cleanError, e.message)
                                }
                            }
                        }
                    }

                    "cancelSearch" -> {
                        val searchId = call.argument<String>("searchId")?.trim() ?: ""
                        if (searchId.isEmpty()) {
                            safeResult.success(false)
                            return@setMethodCallHandler
                        }
                        executor.execute {
                            try {
                                YoutubeDL.getInstance().destroyProcessById(searchId)
                            } catch (e: Exception) {
                                android.util.Log.w(TAG, "cancelSearch destroyProcessById notice: ${e.message}")
                            }
                            safeResult.success(true)
                        }
                    }

                    "setBackgroundConfig" -> {
                        val enabled = call.argument<Boolean>("enableBackgroundProcessing") ?: true
                        val notifications = call.argument<Boolean>("backgroundNotifications") ?: true
                        RamenBackgroundService.enableBackgroundProcessing = enabled
                        RamenBackgroundService.enableBackgroundNotifications = notifications
                        RamenBackgroundService.syncService(applicationContext)
                        safeResult.success(true)
                    }

                    "isIgnoringBatteryOptimizations" -> {
                        val pm = applicationContext.getSystemService(android.content.Context.POWER_SERVICE) as android.os.PowerManager
                        val ignoring = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
                            pm.isIgnoringBatteryOptimizations(applicationContext.packageName)
                        } else {
                            true
                        }
                        safeResult.success(ignoring)
                    }

                    "requestIgnoreBatteryOptimizations" -> {
                        try {
                            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
                                val pm = applicationContext.getSystemService(android.content.Context.POWER_SERVICE) as android.os.PowerManager
                                if (!pm.isIgnoringBatteryOptimizations(applicationContext.packageName)) {
                                    val intent = Intent(android.provider.Settings.ACTION_REQUEST_IGNORE_BATTERY_OPTIMIZATIONS).apply {
                                        data = Uri.parse("package:${applicationContext.packageName}")
                                    }
                                    startActivity(intent)
                                }
                            }
                            safeResult.success(true)
                        } catch (e: Exception) {
                            android.util.Log.w(TAG, "requestIgnoreBatteryOptimizations fallback: ${e.message}")
                            try {
                                val fallbackIntent = Intent(android.provider.Settings.ACTION_IGNORE_BATTERY_OPTIMIZATION_SETTINGS)
                                startActivity(fallbackIntent)
                                safeResult.success(true)
                            } catch (e2: Exception) {
                                safeResult.error("BATTERY_OPT_ERROR", e2.message)
                            }
                        }
                    }

                    "resolveTaskFile" -> {
                        val title = call.argument<String>("title")?.trim() ?: ""
                        val outDir = call.argument<String>("outDir")?.trim() ?: ""
                        val ext = call.argument<String>("ext")?.trim() ?: ""
                        executor.execute {
                            try {
                                val targetDir = resolveTargetDirectory(outDir)
                                val safeBaseTitle = title.replace(Regex("""[\\/:*?"<>|]"""), "_").take(120)
                                val matched = findMatchingOutputFile(
                                    targetDir = targetDir,
                                    rawTitle = title,
                                    safeBaseTitle = safeBaseTitle,
                                    preferredExt = ext,
                                    downloadStartTimeMs = 0L,
                                    beforeSnapshot = emptySet()
                                )
                                safeResult.success(matched?.absolutePath)
                            } catch (e: Exception) {
                                safeResult.success(null)
                            }
                        }
                    }

                    "startDownload" -> {
                        val taskId = call.argument<String>("taskId")?.trim() ?: ""
                        val rawUrl = call.argument<String>("url")?.trim() ?: ""
                        val title = call.argument<String>("title")?.trim()?.takeIf { it.isNotEmpty() } ?: rawUrl
                        val outDir = call.argument<String>("outDir")?.trim() ?: ""
                        val args = call.argument<List<String>>("args") ?: emptyList()

                        if (taskId.isEmpty() || rawUrl.isEmpty()) {
                            safeResult.error("INVALID_ARGS", "Both taskId and url are required and cannot be empty")
                            return@setMethodCallHandler
                        }

                        activeTasks[taskId] = "DOWNLOADING"
                        cancelledTasks.remove(taskId)
                        RamenBackgroundService.onDownloadStarted(applicationContext, taskId, title)
                        safeResult.success(true)

                        executor.execute {
                            try {
                                ensureEngineInitialized()

                                val targetDir = resolveTargetDirectory(outDir)
                                val downloadStartTimeMs = System.currentTimeMillis() - 2000L
                                val beforeSnapshot = targetDir.listFiles()
                                    ?.filter { it.isFile }
                                    ?.map { "${it.name}:${it.length()}:${it.lastModified()}" }
                                    ?.toSet() ?: emptySet()

                                val request = YoutubeDLRequest(rawUrl)
                                val safeBaseTitle = title.replace(Regex("""[\\/:*?"<>|]"""), "_").take(120)
                                val outTemplate = File(targetDir, "%(title).200B.%(ext)s").absolutePath
                                request.addOption("-o", outTemplate)
                                request.addOption("-P", "temp:${getTempDownloadDir().absolutePath}")

                                val configFile = getOrCreateConfigFile()
                                if (!args.contains("--config-locations")) {
                                    request.addOption("--config-locations", configFile.absolutePath)
                                }
                                applyOptions(request, args)

                                val speedRegex = Regex("""at\s+([0-9.]+\s*[kKmMgG]?[iI]?[bB]/s)""")
                                val liveElapsedRegex = Regex("""\(([0-9:]+)\)""")
                                var detectedFilePath: String? = null

                                YoutubeDL.getInstance().execute(request, taskId) { progress, etaInSeconds, line ->
                                    if (cancelledTasks.contains(taskId)) {
                                        return@execute
                                    }
                                    val rawLine = line ?: ""
                                    parseFilePathFromYtDlpLine(rawLine)?.let { parsed ->
                                        detectedFilePath = parsed
                                    }
                                    val speedMatch = speedRegex.find(rawLine)
                                    val speed = speedMatch?.groupValues?.getOrNull(1) ?: ""
                                    val safeProgress = if (progress < 0f) 0.0 else progress.toDouble()
                                    val liveElapsed = liveElapsedRegex.find(rawLine)?.groupValues?.getOrNull(1)
                                    val etaValue: Any = if (etaInSeconds < 0 && liveElapsed != null) {
                                        "LIVE $liveElapsed"
                                    } else if (etaInSeconds < 0) {
                                        "LIVE"
                                    } else {
                                        etaInSeconds
                                    }

                                    RamenBackgroundService.onDownloadProgress(
                                        applicationContext,
                                        taskId,
                                        safeProgress,
                                        speed
                                    )

                                    emitEvent(
                                        mapOf(
                                            "taskId" to taskId,
                                            "status" to "DOWNLOADING",
                                            "progress" to safeProgress,
                                            "speed" to speed,
                                            "eta" to etaValue,
                                            "filePath" to detectedFilePath,
                                            "log" to rawLine
                                        )
                                    )
                                }

                                if (cancelledTasks.remove(taskId)) {
                                    activeTasks.remove(taskId)
                                    RamenBackgroundService.onDownloadFinished(applicationContext, taskId, false, "Cancelled")
                                    emitEvent(
                                        mapOf(
                                            "taskId" to taskId,
                                            "status" to "CANCELLED",
                                            "progress" to 0.0,
                                            "eta" to 0,
                                            "log" to "Download was cancelled."
                                        )
                                    )
                                    return@execute
                                }

                                val resolvedFile = detectedFilePath
                                    ?.let { File(it) }
                                    ?.takeIf { it.exists() && it.isFile && !isTemporaryDownloadFile(it) }
                                    ?: findMatchingOutputFile(
                                        targetDir = targetDir,
                                        rawTitle = title,
                                        safeBaseTitle = safeBaseTitle,
                                        preferredExt = "",
                                        downloadStartTimeMs = downloadStartTimeMs,
                                        beforeSnapshot = beforeSnapshot
                                    )

                                activeTasks.remove(taskId)
                                RamenBackgroundService.onDownloadFinished(applicationContext, taskId, true)
                                emitEvent(
                                    mapOf(
                                        "taskId" to taskId,
                                        "status" to "COMPLETED",
                                        "progress" to 100.0,
                                        "speed" to "0.0 KB/s",
                                        "eta" to 0,
                                        "filePath" to resolvedFile?.absolutePath,
                                        "fileSize" to resolvedFile?.length(),
                                        "log" to "Download finished successfully."
                                    )
                                )

                                // Index downloaded file(s) into Android system MediaStore
                                try {
                                    val recentFiles = targetDir.listFiles()?.filter {
                                        it.isFile && (System.currentTimeMillis() - it.lastModified()) < 300000
                                    }?.map { it.absolutePath }?.toTypedArray()
                                    if (!recentFiles.isNullOrEmpty()) {
                                        MediaScannerConnection.scanFile(applicationContext, recentFiles, null) { path, uri ->
                                            android.util.Log.d(TAG, "MediaScanner indexed: $path -> $uri")
                                        }
                                    }
                                } catch (scanErr: Exception) {
                                    android.util.Log.w(TAG, "MediaScanner indexing warning: ${scanErr.message}")
                                }
                            } catch (e: Exception) {
                                activeTasks.remove(taskId)
                                if (cancelledTasks.remove(taskId) || isCancellationException(e)) {
                                    RamenBackgroundService.onDownloadFinished(applicationContext, taskId, false, "Cancelled")
                                    emitEvent(
                                        mapOf(
                                            "taskId" to taskId,
                                            "status" to "CANCELLED",
                                            "progress" to 0.0,
                                            "eta" to 0,
                                            "log" to "Download was cancelled by user."
                                        )
                                    )
                                } else {
                                    android.util.Log.e(TAG, "Download failed for task $taskId: ${e.message}", e)
                                    val cleanError = extractCleanErrorMessage(e)
                                    RamenBackgroundService.onDownloadFinished(applicationContext, taskId, false, cleanError)
                                    emitEvent(
                                        mapOf(
                                            "taskId" to taskId,
                                            "status" to "FAILED",
                                            "error" to cleanError,
                                            "log" to (e.message ?: cleanError)
                                        )
                                    )
                                }
                            }
                        }
                    }

                    "cancelDownload" -> {
                        val taskId = call.argument<String>("taskId")?.trim() ?: ""
                        if (taskId.isEmpty()) {
                            safeResult.error("INVALID_TASK_ID", "TaskId cannot be empty")
                            return@setMethodCallHandler
                        }

                        cancelledTasks.add(taskId)
                        activeTasks.remove(taskId)
                        RamenBackgroundService.onDownloadFinished(applicationContext, taskId, false, "Cancelled")

                        executor.execute {
                            try {
                                YoutubeDL.getInstance().destroyProcessById(taskId)
                            } catch (e: Exception) {
                                android.util.Log.w(TAG, "destroyProcessById error: ${e.message}")
                            }

                            emitEvent(
                                mapOf(
                                    "taskId" to taskId,
                                    "status" to "CANCELLED",
                                    "progress" to 0.0,
                                    "eta" to 0,
                                    "log" to "Download cancelled by user."
                                )
                            )
                            safeResult.success(true)
                        }
                    }

                    else -> safeResult.notImplemented()
                }
            }
    }

    private fun resolveTargetDirectory(outDir: String): File {
        return when {
            outDir.isNotEmpty() && File(outDir).isAbsolute -> File(outDir)
            outDir.isNotEmpty() && (outDir == "Download/Ramen" || outDir.startsWith("Download/")) -> {
                val sub = if (outDir == "Download/Ramen") "Ramen" else outDir.removePrefix("Download/")
                File(
                    android.os.Environment.getExternalStoragePublicDirectory(
                        android.os.Environment.DIRECTORY_DOWNLOADS
                    ),
                    sub
                )
            }
            outDir.isNotEmpty() -> File(android.os.Environment.getExternalStorageDirectory(), outDir)
            else -> File(
                android.os.Environment.getExternalStoragePublicDirectory(
                    android.os.Environment.DIRECTORY_DOWNLOADS
                ),
                "Ramen"
            )
        }.apply {
            if (!exists()) {
                mkdirs()
            }
        }
    }

    private fun isTemporaryDownloadFile(file: File): Boolean {
        val lower = file.name.lowercase()
        return lower.endsWith(".part") ||
            lower.endsWith(".ytdl") ||
            lower.endsWith(".temp") ||
            lower.endsWith(".aria2")
    }

    private fun parseFilePathFromYtDlpLine(line: String): String? {
        val trimmed = line.trim()
        if (trimmed.isEmpty()) return null

        val patterns = listOf(
            Regex("""\[Merger\] Merging formats into "(.+?)""""),
            Regex("""\[VideoRemuxer\] Remuxing video from \S+ to "(.+?)""""),
            Regex("""\[FixupM3u8\] Fixing MPEG-TS in MP4 container of "(.+?)""""),
            Regex("""\[ExtractAudio\] Destination:\s+(.+)$"""),
            Regex("""\[download\] Destination:\s+(.+)$"""),
            Regex("""\[download\]\s+(.+?)\s+has already been downloaded""")
        )

        for (regex in patterns) {
            val match = regex.find(trimmed)
            if (match != null) {
                val path = match.groupValues[1].trim().trim('"')
                if (path.isNotEmpty() && !path.contains("/ytdlp_temp/")) {
                    return path
                }
            }
        }
        return null
    }

    private fun findMatchingOutputFile(
        targetDir: File,
        rawTitle: String,
        safeBaseTitle: String,
        preferredExt: String,
        downloadStartTimeMs: Long,
        beforeSnapshot: Set<String>
    ): File? {
        val files = targetDir.listFiles()?.filter {
            it.isFile && !isTemporaryDownloadFile(it) && it.length() > 0L
        } ?: return null

        if (files.isEmpty()) return null

        // 1. If we have a snapshot from before the download started, look for newly created/modified files first
        if (downloadStartTimeMs > 0L) {
            val newlyModified = files.filter { f ->
                val sig = "${f.name}:${f.length()}:${f.lastModified()}"
                !beforeSnapshot.contains(sig) && f.lastModified() >= downloadStartTimeMs
            }
            if (newlyModified.isNotEmpty()) {
                return newlyModified.maxByOrNull { it.lastModified() }
            }
        }

        // 2. Match by title prefix or normalized alphanumeric tokens
        val normalizedQuery = safeBaseTitle.lowercase().replace(Regex("""[^a-z0-9]"""), "")
        val rawNorm = rawTitle.lowercase().replace(Regex("""[^a-z0-9]"""), "")
        val cleanExt = preferredExt.lowercase().removePrefix(".")

        val scored = files.mapNotNull { file ->
            val nameWithoutExt = file.nameWithoutExtension
            val normFile = nameWithoutExt.lowercase().replace(Regex("""[^a-z0-9]"""), "")
            var score = 0
            if (nameWithoutExt.equals(rawTitle, ignoreCase = true) ||
                nameWithoutExt.equals(safeBaseTitle, ignoreCase = true)
            ) {
                score += 100
            } else if (normalizedQuery.length >= 4 &&
                (normFile.contains(normalizedQuery.take(24)) || normalizedQuery.contains(normFile.take(24)))
            ) {
                score += 60
            } else if (rawNorm.length >= 4 &&
                (normFile.contains(rawNorm.take(24)) || rawNorm.contains(normFile.take(24)))
            ) {
                score += 50
            }
            if (score > 0 && cleanExt.isNotEmpty() && file.extension.equals(cleanExt, ignoreCase = true)) {
                score += 20
            }
            if (score > 0) Pair(file, score) else null
        }

        if (scored.isNotEmpty()) {
            return scored.maxWithOrNull(
                compareBy<Pair<File, Int>> { it.second }.thenBy { it.first.lastModified() }
            )?.first
        }

        // 3. Fallback during active download completion: return most recently modified file if within last 2 minutes
        if (downloadStartTimeMs > 0L) {
            return files.filter { it.lastModified() >= downloadStartTimeMs - 60000L }
                .maxByOrNull { it.lastModified() }
        }

        return null
    }

    private fun applyOptions(request: YoutubeDLRequest, args: List<String>) {
        var i = 0
        while (i < args.size) {
            val arg = args[i].trim()
            if (arg.isEmpty()) {
                i++
                continue
            }

            if (arg.contains("=")) {
                val key = arg.substringBefore("=").trim()
                var value = arg.substringAfter("=").trim()
                // Map aria2c to libaria2c.so for youtubedl-android
                if ((key == "--downloader" || key == "--external-downloader") && value.equals("aria2c", ignoreCase = true)) {
                    value = "libaria2c.so"
                }
                if (key.isNotEmpty()) {
                    if (value.isNotEmpty()) {
                        request.addOption(key, value)
                    } else {
                        request.addOption(key)
                    }
                }
                i++
            } else if (arg.startsWith("-")) {
                if (i + 1 < args.size && !args[i + 1].trim().startsWith("-")) {
                    var value = args[i + 1].trim()
                    // Map aria2c to libaria2c.so for youtubedl-android
                    if ((arg == "--downloader" || arg == "--external-downloader") && value.equals("aria2c", ignoreCase = true)) {
                        value = "libaria2c.so"
                    }
                    request.addOption(arg, value)
                    i += 2
                } else {
                    request.addOption(arg)
                    i++
                }
            } else {
                request.addOption(arg)
                i++
            }
        }
    }

    private fun isCancellationException(e: Throwable): Boolean {
        if (e is InterruptedException) return true
        val msg = (e.message ?: "").lowercase()
        return msg.contains("process destroyed") ||
               msg.contains("interrupted") ||
               msg.contains("canceled") ||
               msg.contains("cancelled")
    }

    private fun extractCleanErrorMessage(e: Throwable): String {
        val message = e.message ?: e.localizedMessage ?: "Operation failed"
        val lines = message.lines()
        val errorLines = lines.filter { it.trim().startsWith("ERROR:", ignoreCase = true) }
        if (errorLines.isNotEmpty()) {
            return errorLines.last().trim().substringAfter(":").trim()
        }
        val meaningful = lines.firstOrNull { line ->
            val t = line.trim()
            t.isNotBlank() &&
                !t.startsWith("WARNING:", ignoreCase = true) &&
                !t.startsWith("Traceback", ignoreCase = true) &&
                !t.startsWith("File \"", ignoreCase = true)
        }?.trim()
        return meaningful ?: message
    }

    override fun onDestroy() {
        RamenBackgroundService.isActivityInForeground = false
        if (!RamenBackgroundService.enableBackgroundProcessing) {
            // Cancel ongoing active download processes only when background execution is disabled
            for (taskId in activeTasks.keys) {
                try {
                    YoutubeDL.getInstance().destroyProcessById(taskId)
                } catch (_: Exception) {}
            }
            activeTasks.clear()
            cancelledTasks.clear()
        }
        super.onDestroy()
    }
